<h2 class="wp-block-heading has-text-align-center ef-section-title" id="notre-ecole">Notre École</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>L'école existe depuis maintenant 5 ans à Sherbrooke. J'ai commencé cette aventure seul en donnant des cours de guitare à domicile avant d'ouvrir mon propre local. Aujourd'hui, nous sommes une équipe de quatre professeurs, moi inclus, et nous enseignons plusieurs instruments différents.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Notre objectif est de faire de l'école un endroit accueillant où chacun peut avoir du plaisir à apprendre la musique, qu'il s'agisse d'enfants de 4 ans ou d'adultes qui ont toujours rêvé de jouer d'un instrument sans jamais en avoir eu l'occasion.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Nous adaptons notre approche à chaque élève, car nous croyons qu'il n'existe pas une seule bonne façon d'apprendre la musique. Chaque personne progresse à son rythme et mérite un enseignement qui correspond à ses besoins et à ses objectifs.</p>
